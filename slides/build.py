"""Check slides/deck.css against tokens.css, then build slides/preview.html from slides/layouts/.

Run from the repository root:  python3 slides/build.py
Add --png to also screenshot each layout into slides/thumbs/ (needs Chrome or Chromium, as social/render.py does).
"""
import html
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path
from tempfile import TemporaryDirectory

slides = Path(__file__).resolve().parent
root = slides.parent


def block(css, selector):
    """Custom properties declared in the first rule whose selector is exactly `selector`."""
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for sel, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        if sel.strip() == selector:
            return dict(re.findall(r"(--[\w-]+)\s*:\s*([^;]+);", body))
    raise SystemExit(f"No rule for {selector!r}")


# 1. Every --nc-* colour a slide theme declares must match tokens.css for that theme.
tokens = (root / "tokens.css").read_text()
deck = (slides / "deck.css").read_text()
pairs = [
    (':root, [data-theme="dark"]', "section"),
    ('[data-theme="light"]', "section.light"),
]
problems = []
for token_sel, deck_sel in pairs:
    want = block(tokens, token_sel)
    have = block(deck, deck_sel)
    for name, value in have.items():
        if name in want and want[name].strip().upper() != value.strip().upper():
            problems.append(f"{deck_sel} {name}: {value.strip()} in deck.css, {want[name].strip()} in tokens.css")
if problems:
    print("deck.css is out of step with tokens.css:")
    print("\n".join(f"  {p}" for p in problems))
    sys.exit(1)
print("deck.css colours match tokens.css")

# 2. preview.html: every layout at full size, scaled to fit the window.
layouts = sorted((slides / "layouts").glob("*.html"))
sections = []
for f in layouts:
    src = f.read_text()
    # Layouts use paths relative to slides/layouts/; the preview sits one folder up.
    src = src.replace('src="../../assets/', 'src="../assets/')
    notes = re.search(r"<aside>(.*?)</aside>", src, re.S)
    src = re.sub(r"<aside>.*?</aside>\n?", "", src, flags=re.S)
    sections.append(
        f'<figure class="frame" id="{f.stem}"><div class="stage">{src}</div>'
        f'<figcaption><code>layouts/{f.name}</code> {html.escape(notes.group(1)) if notes else ""}</figcaption></figure>'
    )

page = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>NanoClaw slide layouts</title>
<!-- Generated by slides/build.py from slides/layouts/. Edit the layouts, then run the script again. -->
<link rel="icon" href="../assets/app-icon/favicon.svg" type="image/svg+xml">
<style>
@font-face {{ font-family: "Inter"; src: url("../assets/fonts/Inter-latin.woff2") format("woff2"); font-weight: 100 900; font-display: swap; }}
@font-face {{ font-family: "JetBrains Mono"; src: url("../assets/fonts/JetBrainsMono-latin.woff2") format("woff2"); font-weight: 100 800; font-display: swap; }}
html {{ background: #0C1213; color: #EAF4F2; font-family: "Inter", system-ui, sans-serif; }}
body {{ margin: 0; padding: 48px 16px 96px; }}
header {{ max-width: 1280px; margin: 0 auto 40px; }}
header h1 {{ font-size: 36px; line-height: 44px; letter-spacing: -0.02em; margin: 0 0 8px; }}
header p {{ color: #93A9A6; margin: 0; font-size: 16px; line-height: 26px; }}
header a {{ color: #56EDD6; }}
.frame {{ max-width: 1280px; margin: 0 auto 48px; }}
.stage {{ aspect-ratio: 16 / 9; position: relative; overflow: hidden; border-radius: 10px; border: 1px solid #263234; }}
.stage > section {{ position: absolute; left: 0; top: 0; transform-origin: 0 0; transform: scale(var(--scale, 0.6667)); }}
figcaption {{ color: #93A9A6; font-size: 14px; line-height: 22px; margin-top: 12px; }}
figcaption code {{ font-family: "JetBrains Mono", ui-monospace, monospace; color: #EAF4F2; margin-right: 8px; }}
</style>
<link rel="stylesheet" href="deck.css">
</head>
<body>
<header>
<h1>NanoClaw slide layouts</h1>
<p>{len(layouts)} layouts on a 1920 × 1080 canvas, styled by <a href="deck.css">deck.css</a>. Rules are in <a href="../BRAND.md#slides">BRAND.md › Slides</a>; how to start a deck is in <a href="README.md">slides/README.md</a>.</p>
</header>
{chr(10).join(sections)}
<script>
// Scale each 1920px slide to the width of its frame
const fit = () => document.querySelectorAll(".stage").forEach(s => s.style.setProperty("--scale", s.clientWidth / 1920));
addEventListener("resize", fit); fit();
</script>
</body>
</html>
"""
(slides / "preview.html").write_text(page)
print(f"wrote slides/preview.html with {len(layouts)} layouts")

# 3. Optional thumbnails
if "--png" in sys.argv:
    browser = os.getenv("CHROME_BIN") or shutil.which("chromium") or shutil.which("google-chrome")
    if not browser:
        browser = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"
    if not Path(browser).is_file():
        raise SystemExit("Set CHROME_BIN to your Chrome or Chromium executable.")
    thumbs = slides / "thumbs"
    thumbs.mkdir(exist_ok=True)
    with TemporaryDirectory() as tmp:
        for f in layouts:
            single = Path(tmp) / f"{f.stem}.html"
            src = re.sub(r"<aside>.*?</aside>", "", f.read_text(), flags=re.S)
            src = src.replace('src="../../assets/', f'src="{(root / "assets").as_uri()}/')
            single.write_text(
                "<!doctype html><meta charset='utf-8'><style>"
                f"@font-face{{font-family:'Inter';src:url('{(root / 'assets/fonts/Inter-latin.woff2').as_uri()}');font-weight:100 900}}"
                f"@font-face{{font-family:'JetBrains Mono';src:url('{(root / 'assets/fonts/JetBrainsMono-latin.woff2').as_uri()}');font-weight:100 800}}"
                "body{margin:0}*{animation:none!important}</style>"
                f"<link rel='stylesheet' href='{(slides / 'deck.css').as_uri()}'>{src}"
            )
            subprocess.run([
                browser, "--headless", "--disable-background-networking", "--hide-scrollbars",
                "--allow-file-access-from-files", "--window-size=1920,1080", "--force-device-scale-factor=0.5",
                "--virtual-time-budget=5000", f"--user-data-dir={tmp}/profile",
                f"--screenshot={thumbs / (f.stem + '.png')}", single.as_uri(),
            ], check=True, capture_output=True)
            print(f"wrote slides/thumbs/{f.stem}.png")
